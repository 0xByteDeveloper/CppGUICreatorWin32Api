    // =========================================================================
    // helpers
    // =========================================================================
    // narrow to ASCII (replace non-ascii with '_') for generated comments
    static std::wstring NarrowAscii(std::wstring s)
    {
        for (auto& c : s) if ((unsigned)c >= 0x80) c = L'_';
        return s;
    }

    // =========================================================================
    // HandlerName
    // =========================================================================
    std::wstring HandlerName(const std::wstring& owner, const std::wstring& event)
    {
        std::wstring o = NormalizeIdentW(owner);
        std::wstring e = NormalizeIdentW(event);
        if (o.empty()) o = L"Form1";
        if (e.empty()) e = L"Click";
        return o + L"_" + e;
    }

    // =========================================================================
    // BuildHandlerBlock — ASCII-only stub with the Win32 sender/e equivalents
    // =========================================================================
    std::wstring BuildHandlerBlock(const std::wstring& owner, const std::wstring& event,
                                   bool isForm)
    {
        std::wstring h = HandlerName(owner, event);
        std::wstring kind = isForm ? L"Form" : owner;
        std::wstring out;
        out += L"\n";
        out += L"// ------------------------------------------------------------------\n";
        out += L"// Generated by CppGUICreatorWin32Api  (pure Win32 - no .NET types)\n";
        out += L"// Event  : " + NarrowAscii(event) + L"\n";
        out += L"// Owner  : " + NarrowAscii(kind) + L"\n";
        out += L"// Win32 equivalents of the CLR sender / e pair (inspectable + controllable):\n";
        out += L"//   sender->TypeName / sender->Name / sender->Hwnd / sender->Id\n";
        out += L"//   e->Message / e->WParam / e->LParam / e->X / e->Y / e->Handled\n";
        out += L"//   (set e->Handled = true to stop default processing)\n";
        out += L"// ------------------------------------------------------------------\n";
        out += L"void " + h + L"(W32Object* sender, W32EventArgs* e)\n";
        out += L"{\n";
        out += L"    // TODO: add your code here\n";
        out += L"    (void)sender; (void)e;\n";
        out += L"}\n";
        out += L"\n";
        return out;
    }

    // =========================================================================
    // EnsureRuntimeInclude
    // =========================================================================
    std::wstring EnsureRuntimeInclude(const std::wstring& content)
    {
        if (content.find(L"W32GuiRuntime.h") != std::wstring::npos)
            return content;
        static const wchar_t* inc =
            L"#include \"W32GuiRuntime.h\"   // Win32 sender/e runtime (CppGUICreatorWin32Api)\n";

        // insert after the LAST top-of-file #include line (safe for stdafx pch)
        size_t lastIncEnd = std::wstring::npos;
        size_t pos = 0;
        while (true) {
            size_t p = content.find(L"#include", pos);
            if (p == std::wstring::npos) break;
            bool lineStart = (p == 0) || content[p - 1] == L'\n';
            if (lineStart) {
                size_t e = content.find(L'\n', p);
                if (e == std::wstring::npos) { lastIncEnd = content.size(); break; }
                lastIncEnd = e + 1;
                pos = e + 1;
            } else {
                pos = p + 8;
            }
        }
        if (lastIncEnd == std::wstring::npos) {
            // no includes: put after leading comments / blank lines at top
            pos = 0;
            while (pos < content.size()) {
                size_t e = content.find(L'\n', pos);
                if (e == std::wstring::npos) { pos = content.size(); break; }
                std::wstring line = content.substr(pos, e - pos);
                std::wstring t = TrimW(line);
                if (t.empty() || StartsWithW(t, L"//")) pos = e + 1;
                else break;
            }
            return content.substr(0, pos) + inc + content.substr(pos);
        }
        return content.substr(0, lastIncEnd) + inc + content.substr(lastIncEnd);
    }

    // =========================================================================
    // EnsureHandlerInContent (pure, unit-testable)
    // =========================================================================
    EnsureResult EnsureHandlerInContent(const std::wstring& content,
                                        const std::wstring& owner,
                                        const std::wstring& event,
                                        bool isForm)
    {
        EnsureResult r;
        r.handler = HandlerName(owner, event);
        std::wstring needle = L"void " + r.handler + L"(";

        // 1) runtime include (not counted as "changed" for the handler check)
        std::wstring withInc = EnsureRuntimeInclude(content);
        r.incAdded = (withInc != content);

        // 2) existing handler?
        size_t p = LowerW(withInc).find(LowerW(needle));
        if (p != std::wstring::npos) {
            r.existed = true;
            r.fileChanged = r.incAdded;
            r.line = 1;
            for (size_t i = 0; i < p; i++) if (withInc[i] == L'\n') r.line++;
            return r;
        }

        // 3) append stub at the very end (user code above stays untouched)
        std::wstring block = ReplaceW(BuildHandlerBlock(owner, event, isForm), L"\n", L"\r\n");
        std::wstring out = withInc;
        if (!out.empty() && out.back() != L'\n') out += L"\r\n";
        out += block;

        // locate the appended definition and compute its 1-based line
        size_t vp = LowerW(out).find(LowerW(needle));
        r.existed = false;
        r.fileChanged = true;
        r.line = 0;
        if (vp != std::wstring::npos) {
            r.line = 1;
            for (size_t i = 0; i < vp; i++) if (out[i] == L'\n') r.line++;
        }
        return r;
    }

    // =========================================================================
    // EnsureHandler (file-level)
    // =========================================================================
    EnsureResult EnsureHandler(const std::wstring& cppPath,
                               const std::wstring& owner,
                               const std::wstring& event,
                               bool isForm,
                               const std::wstring& runtimeHeaderSourceDir)
    {
        EnsureResult r;
        r.handler = HandlerName(owner, event);
        std::string bytes;
        if (!ReadBinFile(cppPath, bytes)) {
            r.error = L"cpp dosyasi okunamadi: " + cppPath;
            return r;
        }
        bool hadBom = bytes.size() >= 3 &&
                      (unsigned char)bytes[0] == 0xEF &&
                      (unsigned char)bytes[1] == 0xBB &&
                      (unsigned char)bytes[2] == 0xBF;
        std::wstring content = Utf8ToW(hadBom ? bytes.substr(3) : bytes);

        // pure transform gives us the exact result incl. line number
        EnsureResult tr = EnsureHandlerInContent(content, owner, event, isForm);
        r = tr;

        if (tr.fileChanged) {
            // recompute full output exactly like the pure function does
            std::wstring out = EnsureRuntimeInclude(content);
            size_t p = LowerW(out).find(LowerW(L"void " + r.handler + L"("));
            if (p == std::wstring::npos) {
                std::wstring block = ReplaceW(BuildHandlerBlock(owner, event, isForm), L"\n", L"\r\n");
                if (!out.empty() && out.back() != L'\n') out += L"\r\n";
                out += block;
            }
            std::string ob = WToUtf8(out);
            std::string finalBytes = "\xEF\xBB\xBF" + ob;   // UTF-8 BOM + CRLF content
            // backup first — user code is precious
            WriteBinFile(cppPath + L".bak", bytes, false);
            if (!WriteBinFile(cppPath, finalBytes, false)) {
                r.error = L"cpp dosyasina yazilamadi: " + cppPath;
                return r;
            }
            r.fileChanged = true;
        }

        // copy runtime header next to the cpp when missing
        std::wstring dir = DirFromPathW(cppPath);
        std::wstring dstHeader = dir + L"\\W32GuiRuntime.h";
        if (!FileExistsW(dstHeader) && !runtimeHeaderSourceDir.empty()) {
            std::string hdr;
            std::wstring src = runtimeHeaderSourceDir + L"\\W32GuiRuntime.h";
            if (ReadBinFile(src, hdr)) {
                if (WriteBinFile(dstHeader, hdr, false))
                    r.runtimeCopied = true;
            }
        }
        return r;
    }

    // =========================================================================
    // ExportMainCpp — standalone Win32 app for W32GuiRuntime.h
    // =========================================================================
    static std::wstring KindExprFor(const std::wstring& type)
    {
        if (type == L"Button")          return L"W32K_BUTTON";
        if (type == L"Label")           return L"W32K_LABEL";
        if (type == L"TextBox")         return L"W32K_TEXTBOX";
        if (type == L"CheckBox")        return L"W32K_CHECKBOX";
        if (type == L"RadioButton")     return L"W32K_RADIO";
        if (type == L"GroupBox")        return L"W32K_GROUPBOX";
        if (type == L"PictureBox")      return L"W32K_PICTUREBOX";
        if (type == L"ComboBox")        return L"W32K_COMBOBOX";
        if (type == L"ListBox")         return L"W32K_LISTBOX";
        if (type == L"ProgressBar")     return L"W32K_PROGRESS";
        if (type == L"TrackBar")        return L"W32K_TRACKBAR";
        if (type == L"DateTimePicker")  return L"W32K_DATETIME";
        if (type == L"Panel" || type == L"FlowLayoutPanel") return L"W32K_PANEL";
        if (type == L"MenuStrip")       return L"W32K_MENUSTRIP";
        return L"W32K_LABEL";
    }

    std::wstring ExportMainCpp(const FormInfo& f, const std::vector<ControlInstance>& ctrlsIn)
    {
        // self-heal missing/duplicate control ids (layouts may omit them)
        std::vector<ControlInstance> ctrls = ctrlsIn;
        int nextId = 1001;
        for (auto& c : ctrls) {
            if (c.idc <= 1000) {
                bool taken = true;
                while (taken) {
                    taken = false;
                    for (const auto& o : ctrls)
                        if (&o != &c && o.idc == nextId) { taken = true; nextId++; break; }
                }
                c.idc = nextId++;
            }
        }
        std::wstring form = NormalizeIdentW(f.name.empty() ? L"Form1" : f.name);
        std::wstring out;
        out += L"// " + NarrowAscii(form) + L".cpp - generated by CppGUICreatorWin32Api\n";
        out += L"// Pure Win32 API. Build examples:\n";
        out += L"//   MinGW : x86_64-w64-mingw32-g++ -std=c++17 -municode -mwindows " +
                NarrowAscii(form) + L".cpp -o " + NarrowAscii(form) + L".exe\n";
        out += L"//   VS2019: create an empty C++ Windows project and add this file.\n";
        out += L"\n";
        out += L"#include <windows.h>\n";
        out += L"#include \"W32GuiRuntime.h\"\n";
        out += L"\n";
        for (const auto& c : ctrls)
            out += L"#define IDC_" + UpperW(NormalizeIdentW(c.name)) + L" " +
                   std::to_wstring(c.idc ? c.idc : 1000) + L"\n";
        out += L"\n";

        // forward declarations of all bound handlers
        for (const auto& c : ctrls)
            for (const auto& ev : c.events)
                out += L"void " + HandlerName(c.name, ev.first) +
                       L"(W32Object* sender, W32EventArgs* e);\n";
        out += L"void " + HandlerName(form, L"Load") + L"(W32Object* sender, W32EventArgs* e);\n";
        out += L"\n";

        // stub definitions
        for (const auto& c : ctrls) {
            for (const auto& ev : c.events) {
                out += L"void " + HandlerName(c.name, ev.first) +
                       L"(W32Object* sender, W32EventArgs* e)\n{\n    // TODO: " +
                       NarrowAscii(c.name) + L"." + NarrowAscii(ev.first) +
                       L"\n    (void)sender; (void)e;\n}\n\n";
            }
        }
        out += L"void " + HandlerName(form, L"Load") +
               L"(W32Object* sender, W32EventArgs* e)\n{\n    // TODO: form load\n    (void)sender; (void)e;\n}\n\n";

        // layout table
        out += L"static W32ControlDef g_controls[] =\n{\n";
        for (const auto& c : ctrls) {
            std::wstring txt = c.text;
            for (auto& ch : txt) if (ch == L'"') ch = L'\'';
            out += L"    { IDC_" + UpperW(NormalizeIdentW(c.name)) + L", " +
                   KindExprFor(c.type) + L", L\"" + c.name + L"\", L\"" + txt + L"\", " +
                   std::to_wstring(c.x) + L", " + std::to_wstring(c.y) + L", " +
                   std::to_wstring(c.w) + L", " + std::to_wstring(c.h) + L" },\n";
        }
        out += L"};\n\n";

        // bind table
        int bindCount = 0;
        out += L"static W32Bind g_binds[] =\n{\n";
        for (const auto& c : ctrls) {
            for (const auto& ev : c.events) {
                out += L"    { IDC_" + UpperW(NormalizeIdentW(c.name)) + L", L\"" +
                       NarrowAscii(ev.first) + L"\", " + HandlerName(c.name, ev.first) + L" },\n";
                bindCount++;
            }
        }
        out += L"};\n\n";

        out += L"int APIENTRY wWinMain(HINSTANCE, HINSTANCE, PWSTR, int)\n{\n";
        out += L"    return W32RunApp(L\"" + form + L"\", L\"" + f.text + L"\",\n";
        out += L"                     g_controls, " + std::to_wstring(ctrls.size()) + L",\n";
        out += L"                     g_binds, " + std::to_wstring(bindCount) + L");\n";
        out += L"}\n";
        return out;
    }
